export const getLocalizedText = (
  value: LocalizedText,
  locale: Locale,
): string => value[locale] ?? value.en;

export const getMenuItemsByCategory = (
  categoryId: MenuCategoryId,
): readonly MenuItem[] =>
  menuItems.filter((item) => item.categoryId === categoryId);

export const getMenuItemById = (id: MenuItemId): MenuItem | undefined =>
  menuItems.find((item) => item.id === id);

export const getMenuItemBySlug = (slug: string): MenuItem | undefined =>
  menuItems.find((item) => item.slug === slug);

export const getMenuItemStartingPrice = (item: MenuItem): number =>
  item.pricing.kind === "fixed"
    ? item.pricing.price
    : Math.min(...item.pricing.variants.map((variant) => variant.price));

const assertUnique = (values: readonly string[], label: string): void => {
  if (new Set(values).size !== values.length) {
    throw new Error(`Duplicate ${label} found in the canonical Yamzo menu.`);
  }
};

const assertMenuIntegrity = (): void => {
  const categoryIds = new Set<string>(menuCategories.map((category) => category.id));
  const modifierIds = new Set<string>(menuModifierGroups.map((group) => group.id));

  assertUnique(menuCategories.map((category) => category.id), "category ID");
  assertUnique(menuItems.map((item) => item.id), "item ID");
  assertUnique(menuItems.map((item) => item.slug), "item slug");

  for (const item of menuItems) {
    if (!categoryIds.has(item.categoryId)) {
      throw new Error(`Unknown category ${item.categoryId} on ${item.id}.`);
    }

    for (const modifierGroupId of item.modifierGroupIds) {
      if (!modifierIds.has(modifierGroupId)) {
        throw new Error(`Unknown modifier group ${modifierGroupId} on ${item.id}.`);
      }
    }

    const prices =
      item.pricing.kind === "fixed"
        ? [item.pricing.price]
        : item.pricing.variants.map((variant) => variant.price);

    if (prices.some((price) => !Number.isInteger(price) || price <= 0)) {
      throw new Error(`Invalid direct-menu price on ${item.id}.`);
    }
  }
};

assertMenuIntegrity();

